create or replace function public.record_tournament_version()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  next_version integer;
begin
  select coalesce(max(version), 0) + 1
    into next_version
    from public.tournament_versions
   where tournament_id = new.id;

  insert into public.tournament_versions (
    tournament_id,
    version,
    action,
    actor_auth0_sub,
    snapshot
  ) values (
    new.id,
    next_version,
    case when tg_op = 'INSERT' then 'created' else 'updated' end,
    coalesce(new.updated_by, new.created_by),
    to_jsonb(new)
  );

  return new;
end;
$$;

drop trigger if exists tournaments_record_version on public.tournaments;
create trigger tournaments_record_version
after insert or update on public.tournaments
for each row execute function public.record_tournament_version();

