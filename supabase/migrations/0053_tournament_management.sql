create table if not exists public.app_user_permissions (
  auth0_sub text primary key
    references public.app_users(auth0_sub)
    on update cascade
    on delete cascade,
  can_manage_tournaments boolean not null default false,
  updated_at timestamptz not null default now()
);

comment on table public.app_user_permissions is
  'Private application permissions assigned manually by administrators.';

alter table public.app_user_permissions enable row level security;

drop policy if exists "service_manage_app_user_permissions" on public.app_user_permissions;
create policy "service_manage_app_user_permissions"
  on public.app_user_permissions
  for all
  to service_role
  using (true)
  with check (true);

create table if not exists public.tournaments (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 120),
  description text check (description is null or char_length(description) <= 280),
  tournament_date date not null,
  start_time_label text check (start_time_label is null or char_length(start_time_label) <= 80),
  timezone_label text check (timezone_label is null or char_length(timezone_label) <= 80),
  prize_pool_label text check (prize_pool_label is null or char_length(prize_pool_label) <= 80),
  image_url text not null check (
    char_length(image_url) <= 2048
    and lower(image_url) like 'https://%'
  ),
  cta_label text not null check (char_length(cta_label) between 1 and 60),
  cta_url text not null check (
    char_length(cta_url) <= 2048
    and lower(cta_url) like 'https://%'
  ),
  state text not null default 'draft' check (state in ('draft', 'archived')),
  created_by text references public.app_users(auth0_sub) on update cascade on delete set null,
  updated_by text references public.app_users(auth0_sub) on update cascade on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists tournaments_updated_at_idx
  on public.tournaments (updated_at desc);

create index if not exists tournaments_date_idx
  on public.tournaments (tournament_date desc);

alter table public.tournaments enable row level security;

